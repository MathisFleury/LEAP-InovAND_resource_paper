"""
Effects of Age and Sex on group-level anatomical & functional results.

Mass-univariate test of diagnosis x age and diagnosis x sex interactions,
matching the manuscript section "The Effects of Age and Sex". For every
feature (anatomical region / functional edge) we fit, on Autism+NT only:

    age model:  y ~ C(diagnosis)*age_c + C(Sex)   + C(cohort)
    sex model:  y ~ C(diagnosis)*C(Sex) + age_c   + C(cohort)

and keep the single interaction coefficient. p-values are FDR-corrected
(Benjamini-Hochberg) across features, per modality x model, to match the
significance criterion used in the autism-vs-NT scripts. A feature "survives"
if its interaction p_fdr < 0.05.

Outputs (11_age_sex_analysis/outputs/):
  - interaction_<modality>_<model>.csv   per-feature betas/t/p/p_fdr
  - age_sex_interaction_summary.csv       one row per modality x model
"""

