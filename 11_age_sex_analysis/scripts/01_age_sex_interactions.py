def _ggseg_label(feat):
    """Map an anat feature column to a ggseg label + (atlas, metric)."""
    for metric in ('thickness', 'area', 'volume'):
        if feat.endswith('_' + metric) and feat[:3] in ('lh_', 'rh_'):
            hemi = 'left' if feat.startswith('lh_') else 'right'
            region = feat[3:-(len(metric) + 1)]
            return f'{region}_{hemi}', 'dk', metric
    return feat, 'aseg', 'volume'  # subcortical: keep raw label


def export_anat_ggseg_inputs(results, n_autism, n_nt):
    """Per (model, metric, atlas) CSV in the format 03_plot_*.R expects:
    headerless label,t_stat,p_val,cohens_d,p_fdr; FDR recomputed within metric."""
    rdir = os.path.join(OUTPUT_DIR, 'figures', 'r_input_files')
    Path(rdir).mkdir(parents=True, exist_ok=True)
    pd.DataFrame([{'n_autism': n_autism, 'n_nt': n_nt}]).to_csv(
        os.path.join(rdir, 'group_counts.csv'), index=False)

    for model_name, res_df in results.items():
        lab = res_df['feature'].map(_ggseg_label)
        df = res_df.assign(label=[x[0] for x in lab],
                           atlas=[x[1] for x in lab],
                           metric=[x[2] for x in lab])
        for (atlas, metric), grp in df.groupby(['atlas', 'metric']):
            grp = grp.copy()
            grp['p_fdr'] = multipletests(grp['p_value'], method='fdr_bh')[1]
            out = os.path.join(
                rdir, f't_stat_anat_{atlas}_{metric}_interaction_{model_name}.csv')
            grp[['label', 't', 'p_value', 'cohens_d', 'p_fdr']].to_csv(
                out, index=False, header=False)


def main():
    print("=" * 60)
    print("Age & Sex interaction analysis (group level)")
    print("=" * 60)

    summaries = []

    print("\nANATOMICAL")
    anat = load_anat()
    anat = prep_common(anat, 'population_group')
    n_aut, n_nt = int((anat['diag'] == 'Autism').sum()), int((anat['diag'] == 'NT').sum())
    print(f"  n={len(anat)}  Autism={n_aut} NT={n_nt}")
    feats = anat_feature_cols(anat)
    # Global size covariates: mean surface area / mean cortical volume per subject.
    # Regressing these out absorbs the all-region-shared (global) age x diagnosis
    # scaling so a region only survives on its region-specific interaction.
    area_cols = [c for c in feats if c.endswith('_area')]
    vol_cols = [c for c in feats if c.endswith('_volume') and c[:3] in ('lh_', 'rh_')]
    anat['glob_area'] = anat[area_cols].mean(axis=1)
    anat['glob_volume'] = anat[vol_cols].mean(axis=1)

    def anat_cov(f):
        atlas, metric = _ggseg_label(f)[1:]
        if metric == 'area':
            return 'glob_area'
        if metric == 'volume' and atlas == 'dk':
            return 'glob_volume'
        return None  # thickness + subcortical: no global size adjustment

    # FDR within each anatomical metric (thickness/area/cortical-vol/subcort-vol),
    # matching the autism-vs-NT anatomical pipeline.
    anat_family = lambda f: '_'.join(_ggseg_label(f)[1:])  # atlas_metric
    anat_sum, anat_res = run_models(anat, feats, 'anat',
                                    family_of=anat_family, cov_of=anat_cov)
    summaries += anat_sum
    export_anat_ggseg_inputs(anat_res, n_aut, n_nt)

    print("\nFUNCTIONAL")
    # ponytail: ~thousands of OLS fits x2 models, a few min. Vectorize only if
    # this becomes a bottleneck on reruns.
    func = pd.read_csv(FUNC_FILE)
    func = prep_common(func, 'population_group')
    print(f"  n={len(func)}  Autism={int((func['diag']=='Autism').sum())} "
          f"NT={int((func['diag']=='NT').sum())}")
    func_sum, _ = run_models(func, func_feature_cols(func), 'func')
    summaries += func_sum

    df_sum = pd.DataFrame(summaries)
    out = os.path.join(OUTPUT_DIR, 'age_sex_interaction_summary.csv')
    df_sum.to_csv(out, index=False)
    print("\n" + "=" * 60)
    print("SUMMARY")
    print("=" * 60)
    print(df_sum.to_string(index=False))
    print(f"\nSaved: {out}")


if __name__ == '__main__':
    main()
